package EdDYON.guaniao.mixin;

import EdDYON.guaniao.client.particle.PlaceableBlockBreakEffects;
import net.minecraft.client.Minecraft;
import net.minecraft.client.multiplayer.ClientLevel;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.level.block.state.BlockState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * Port of the original Forge IClientBlockExtensions hit/destroy callbacks.
 *
 * In Minecraft 26.2 both effects are generated by ClientLevel instead of
 * ParticleEngine. Cancel ONLY after rendering the original effect for one of
 * the six Guaniao block families; vanilla blocks keep their normal particles.
 */
@Mixin(ClientLevel.class)
public abstract class ClientBlockBreakParticlesMixin {
    @Inject(method = "addDestroyBlockEffect", at = @At("HEAD"), cancellable = true, require = 1)
    private void guaniao$destroyEffect(BlockPos pos, BlockState state, CallbackInfo callback) {
        ClientLevel level = (ClientLevel)(Object)this;
        if (PlaceableBlockBreakEffects.renderDestroy(state, level, pos,
                Minecraft.getInstance().particleEngine)) {
            callback.cancel();
        }
    }

    @Inject(method = "addBreakingBlockEffect", at = @At("HEAD"), cancellable = true, require = 1)
    private void guaniao$hitEffect(BlockPos pos, Direction direction, CallbackInfo callback) {
        ClientLevel level = (ClientLevel)(Object)this;
        BlockState state = level.getBlockState(pos);
        if (PlaceableBlockBreakEffects.renderHit(state, level, pos, direction,
                Minecraft.getInstance().particleEngine)) {
            callback.cancel();
        }
    }
}
